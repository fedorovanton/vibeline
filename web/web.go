// Package web — встроенные в бинарник ресурсы демонстрационного стенда.
//
// Страница встраивается через //go:embed и отдаётся HTTP-слоем как есть.
// Сборки фронтенда нет и не будет: любой шаг сборки означал бы, что стенд
// нельзя поднять из исходников одной командой go build.
//
// Директива //go:embed читает только файлы внутри каталога своего пакета,
// подняться к каталогу выше она не умеет. Поэтому ресурсы и встраивающий их
// пакет лежат рядом, а транспорт получает уже готовый байтовый срез.
package web

import _ "embed"

// Page — HTML демонстрационного стенда: разметка, стили и сценарий в одном
// файле. Внешних ссылок в нём нет — страница обязана открываться на сервере
// без доступа в интернет.
//
//go:embed index.html
var page []byte

// Page возвращает страницу стенда.
//
// Возвращается копия: встроенный срез общий для всех вызывающих, и случайная
// правка одного байта разошлась бы по всем ответам сервера.
func Page() []byte {
	out := make([]byte, len(page))
	copy(out, page)
	return out
}

// PageSize возвращает размер страницы в байтах — для диагностики и тестов.
func PageSize() int { return len(page) }

// presentation — слайды о решении для жюри: те же правила, что у стенда, —
// один файл без внешних ссылок, открывается и с сервиса, и с диска.
//
//go:embed presentation.html
var presentation []byte

// Presentation возвращает копию страницы презентации — по той же причине,
// что и Page.
func Presentation() []byte {
	out := make([]byte, len(presentation))
	copy(out, presentation)
	return out
}

// PresentationSize возвращает размер презентации в байтах.
func PresentationSize() int { return len(presentation) }
