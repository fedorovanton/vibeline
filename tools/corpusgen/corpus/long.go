// piiSentence выбирает предложение с ПД для вставки в длинный текст.
func (g *gen) piiSentence() []piece {
	if g.r.IntN(3) == 0 {
		return multis[g.r.IntN(len(multis))].make(g)
	}
	typ := RequiredTypes[g.r.IntN(len(RequiredTypes))]
	ts := singles[typ]
	return ts[g.r.IntN(len(ts))].make(g)
}

// longRecord собирает запись примерно в target токенов. Смещения считаются тем
// же строителем, что и у коротких записей, поэтому разметка на длинном входе
// проверяется тем же тестом.
func (g *gen) longRecord(target int) Record {
	var b builder
	n := b.addCounted(join(lit("Расшифровка обращения в поддержку, подготовь по ней краткую сводку.")))
	for i := 0; n < target; i++ {
		switch i % 200 {
		case 199:
			b.add(lit("\n\n"))
		default:
			b.add(lit(" "))
		}
		if i%piiEveryNChunks == piiEveryNChunks-1 {
			n += b.addCounted(g.piiSentence())
			continue
		}
		n += b.addCounted(join(lit(pick(g.r, fillers))))
	}
	return b.record(KindLong)
}
