// Package store — хранилище соответствий «payload_id → оригинал и маска».
//
// Соответствие нужно, потому что маска необратима сама по себе: одинаковые
// плейсхолдеры или звёздочки могут скрывать разные значения. Знание payload_id
// авторизацией не является — контроль доступа выполняется выше, в httpapi.
package store

import (
	"errors"
	"time"

	"ai-gateway/internal/pii"
)

// ErrFull возвращается, когда запись не помещается в заданные лимиты.
// Ошибка сознательно отличима: маскирование обязано завершиться отказом,
// а не молча потерять возможность восстановления.
var ErrFull = errors.New("store: превышены лимиты хранилища")

// Record — сохранённое соответствие одной пары «маскирование → демаскирование».
type Record struct {
	// Original — исходная строка, полученная на прямом шаге.
	Original string
	// Masked — строка, возвращённая на прямом шаге.
	Masked string
	// Types — типы ПД, найденные в исходной строке. Значения не хранятся.
	Types pii.Set
	// Consumer — идентификатор системы-потребителя, в области которой
	// создана запись. Демаскирование за пределами этой области запрещено.
	Consumer string
	// CreatedAt — момент создания записи.
	CreatedAt time.Time
}

// Size возвращает приблизительный объём записи в байтах для учёта лимитов.
func (r Record) Size(id string) int64 {
	const overhead = 128 // map bucket, заголовки строк, поля записи
	return int64(len(id) + len(r.Original) + len(r.Masked) + len(r.Consumer) + overhead)
}

// Stats — наблюдаемое состояние хранилища. Значения ПД в статистику не входят.
type Stats struct {
	Entries int
	Bytes   int64
	Evicted uint64
	Expired uint64
}

// Store — контракт хранилища соответствий.
//
// Реализация обязана быть безопасной для конкурентного использования.
// Интерфейс выделен под реальную заменяемую зависимость: первая версия держит
// соответствия в памяти процесса, внешнее хранилище подключается без правки
// вызывающего кода.
type Store interface {
	// Get возвращает запись по идентификатору. Истёкшая запись считается
	// отсутствующей.
	Get(id string) (Record, bool)
	// Put сохраняет запись. Возвращает ErrFull, если лимиты не позволяют.
	Put(id string, rec Record) error
	// Stats возвращает текущее состояние хранилища.
	Stats() Stats
	// Close останавливает фоновые задачи хранилища.
	Close() error
}
