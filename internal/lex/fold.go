package lex

import "unicode"

// Быстрый путь нормализации: класс символа и нижний регистр считаются
// арифметикой, а не поиском по таблицам Unicode.
//
// Причина в профиле: на таблицы уходило больше половины времени разбора.
// Одна и та же руна независимо искалась в четырёх таблицах — IsSpace и
// IsLetter из classify, IsUpper, и ToLower внутри нормализации, — и каждый
// поиск это двоичный спуск по сотням диапазонов.
//
// Быстрый путь закрывает два диапазона, которые и составляют почти весь
// входной текст: ASCII и кириллицу U+0400–U+045F. Всё остальное разбирается
// прежним кодом, поэтому поведение на нём не меняется по построению.
//
// Эквивалентность арифметики таблицам не доказывается рассуждением: она
// проверяется сверкой с эталоном в reference_test.go, включая исчерпывающий
// перебор обоих диапазонов.

// Границы быстрого пути по ведущему байту UTF-8.
//
// Верхняя граница кириллицы — U+045F, а не конец блока. Дальше в таблице
// CaseRanges идёт диапазон U+04C1–U+04CE вида UpperLower, который начинается
// с нечётного кодпойнта, и одиночное исключение U+04C0 со сдвигом на 15.
// Правило «чётный код — заглавная» на них неверно, поэтому весь хвост блока
// уходит на медленный путь. Потери нет: в русском тексте этих букв не бывает.
const (
	cyrLead0 = 0xD0 // U+0400–U+043F
	cyrLead1 = 0xD1 // U+0440–U+047F, из них берём только до U+045F
	cyrMax1  = 0xA0 // первый хвостовой байт за границей быстрого пути
)

// Разряды класса символа в таблице ASCII.
const (
	clsKind  uint8 = 0x03 // совпадает со значениями Kind
	clsSpace uint8 = 0x04 // classify вернула «это не токен»
	clsUpper uint8 = 0x08
)

// asciiFold — класс и свёрнутый байт для каждого символа ASCII.
// Старший байт — класс, младший — символ в нижнем регистре.
var asciiFold [128]uint16

// Таблица выводится из тех самых функций, которые она заменяет. Выписывать её
// константами нельзя: тогда она сможет разойтись с медленным путём — от
// правки classify или от смены версии Go, — и разойдётся молча.
func init() {
	for b := range 128 {
		r := rune(b)
		kind, isKind := classify(r)
		c := uint8(kind)
		if !isKind {
			c |= clsSpace
		}
		if unicode.IsUpper(r) {
			c |= clsUpper
		}
		asciiFold[b] = uint16(c)<<8 | uint16(byte(toLowerFold(r)))
	}
}

// runeInfo — всё, что разбор узнаёт о руне за один шаг.
type runeInfo struct {
	size   int
	kind   Kind
	isKind bool
	upper  bool
	cyr    bool
	lat    bool
}

// foldFast нормализует руну, начинающуюся с байта i, записывает результат в
// dst и возвращает её класс. Второе значение ложно, если руна вне быстрого
// пути: её разбирает общий код.
func foldFast(text string, dst []byte, i int) (runeInfo, bool) {
	b := text[i]
	if b < 0x80 {
		v := asciiFold[b]
		cls := uint8(v >> 8)
		dst[i] = byte(v)
		return runeInfo{
			size:   1,
			kind:   Kind(cls & clsKind),
			isKind: cls&clsSpace == 0,
			upper:  cls&clsUpper != 0,
			// Латиницей ASCII считается так же, как на медленном пути:
			// там условие r < utf8.RuneSelf стоит первым.
			lat: true,
		}, true
	}
	if b != cyrLead0 && b != cyrLead1 {
		return runeInfo{}, false
	}
	// Хвостовой байт обязан быть байтом продолжения. Без этой проверки
	// оборванная последовательность и мусор после ведущего байта разошлись бы
	// с медленным путём, который отдаёт такой байт отдельным знаком.
	if i+1 >= len(text) || text[i+1]&0xC0 != 0x80 {
		return runeInfo{}, false
	}
	if b == cyrLead1 && text[i+1] >= cyrMax1 {
		return runeInfo{}, false
	}

	v := rune(b&0x1F)<<6 | rune(text[i+1]&0x3F) // U+0400–U+045F
	upper := v <= 0x042F
	switch {
	case v == 0x0401 || v == 0x0451: // Ё, ё — проверяется до диапазонов
		v = 0x0435
	case v <= 0x040F: // Ѐ–Џ
		v += 0x50
	case v <= 0x042F: // А–Я
		v += 0x20
	}
	dst[i] = 0xC0 | byte(v>>6)
	dst[i+1] = 0x80 | byte(v&0x3F)

	// Весь диапазон — буквы: таблица _L покрывает U+03F7–U+0481 сплошь.
	return runeInfo{size: 2, kind: KindWord, isKind: true, upper: upper, cyr: true}, true
}
