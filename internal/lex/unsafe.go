package lex

import "unsafe"

// unsafeString отдаёт содержимое буфера как строку без копирования.
//
// Использование ограничено нормализованным буфером Doc: буфер принадлежит Doc,
// не изменяется после разметки и не покидает пределы обработки запроса.
// Экономит одну аллокацию размером со вход на каждый запрос — на текстах до
// 100 000 токенов это заметная доля работы.
func unsafeString(b []byte) string {
	if len(b) == 0 {
		return ""
	}
	return unsafe.String(&b[0], len(b))
}
