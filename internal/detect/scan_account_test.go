// Все номера счетов синтетические: балансовые счета настоящие, остальные
// цифры произвольные, контрольный ключ не подобран. Корреспондентский счёт
// 30101810400000000225 — публичный реквизит банка, персональными данными он
// не является.

// scanAccountText прогоняет сканер счёта по тексту.
func scanAccountText(tb testing.TB, text string) Candidates {
	tb.Helper()
	var out Candidates
	accountScanner{}.Scan(lex.Tokenize(text, nil), digitsTestDicts(tb), &out)
	return out
}

