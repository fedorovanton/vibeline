// TestScanAccountByteOffsets — смещения спана в байтах, кириллица занимает
// два байта на букву.
func TestScanAccountByteOffsets(t *testing.T) {
	const text = "Счёт 40817810099910004312"
	got := scanAccountText(t, text)
	if len(got.Spans) != 1 {
		t.Fatalf("кандидатов %d", len(got.Spans))
	}
	// «Счёт» — четыре кириллические буквы, восемь байт, и пробел.
	if s := got.Spans[0]; s.Start != 9 || s.End != 29 {
		t.Fatalf("спан [%d, %d), ожидался [9, 29)", s.Start, s.End)
	}
}

// TestScanAccountNoAllocs — Scan не аллоцирует: накопитель переиспользуется,
// как в рабочем конвейере.
func TestScanAccountNoAllocs(t *testing.T) {
	doc := lex.Tokenize(accountBenchText(), nil)
	dicts := digitsTestDicts(t)
	var (
		s    accountScanner
		cand Candidates
	)
	s.Scan(doc, dicts, &cand)
	if n := testing.AllocsPerRun(20, func() {
		cand.Reset()
		s.Scan(doc, dicts, &cand)
	}); n != 0 {
		t.Fatalf(msgScanAllocs, n)
	}
}

func BenchmarkScanAccount(b *testing.B) {
	text := accountBenchText()
	doc := lex.Tokenize(text, nil)
	dicts := digitsTestDicts(b)
	var (
		s    accountScanner
		cand Candidates
	)
	s.Scan(doc, dicts, &cand)
	b.SetBytes(int64(len(text)))
	b.ReportAllocs()
	for b.Loop() {
		cand.Reset()
		s.Scan(doc, dicts, &cand)
	}
}

