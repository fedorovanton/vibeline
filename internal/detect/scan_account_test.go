// checkAccountCandidate прогоняет сканер счёта по тексту и проверяет, что
// кандидат-счёт ровно один, со спаном span и уверенностью conf; пустой span —
// кандидата-счёта нет.
func checkAccountCandidate(t *testing.T, text, span string, conf Confidence) {
	t.Helper()
	got := scanAccountText(t, text)
	found := accountSpans(got.Spans)
	if span == "" {
		for _, s := range found {
			t.Errorf("лишний кандидат %q (%s, %s)", text[s.Start:s.End], s.Conf, s.Rule)
		}
		return
	}
	if len(found) != 1 {
		t.Fatalf("кандидатов %d, ожидался один: %s", len(found), formatDigitsSpans(text, got.Spans))
	}
	if s := found[0]; text[s.Start:s.End] != span || s.Conf != conf {
		t.Errorf("кандидат %q %s, ожидался %q %s", text[s.Start:s.End], s.Conf, span, conf)
	}
}

// accountSpans оставляет из кандидатов только счета.
func accountSpans(spans []Span) []Span {
	var found []Span
	for _, s := range spans {
		if s.Type == pii.BankAccount {
			found = append(found, s)
		}
	}
	return found
}

// TestScanAccountCorrDenied — корреспондентский счёт закрыт запретом: подъём
// по кластеру и чужие прочтения тех же цифр его не вернут.
func TestScanAccountCorrDenied(t *testing.T) {
	const text = "к/с 30101810400000000225"
	got := scanAccountText(t, text)
	at := int32(strings.Index(text, "30101"))
	for _, v := range got.Vetos {
		if v.Start <= at && at < v.End && v.Types.Has(pii.BankAccount) {
			return
		}
	}
	t.Fatalf("запрета на корреспондентский счёт нет: %+v", got.Vetos)
}

