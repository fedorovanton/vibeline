// TestScanAddressSingleSpan закрепляет требование «адрес — один спан»:
// цепочка компонентов не должна распадаться на огрызки вокруг каждого «д.».
func TestScanAddressSingleSpan(t *testing.T) {
	const text = "г. Москва, ул. Ленина, д. 5, кв. 12"
	spans := scanAddressText(t, text)
	if len(spans) != 1 {
		t.Fatalf("ожидался один спан, получено %d: %s", len(spans), formatAddressSpans(text, spans))
	}
	if got := text[spans[0].Start:spans[0].End]; got != "Москва, ул. Ленина, д. 5, кв. 12" {
		t.Fatalf("текст спана = %q", got)
	}
}

// TestScanAddressByteOffsets закрепляет требование контракта: смещения спанов
// считаются в байтах, а кириллическая буква занимает два байта.
func TestScanAddressByteOffsets(t *testing.T) {
	const text = "Адрес: Москва, ул. Ленина, д. 5"
	const want = "Москва, ул. Ленина, д. 5"
	spans := scanAddressText(t, text)
	if len(spans) != 1 {
		t.Fatalf("ожидался один спан, получено %d: %s", len(spans), formatAddressSpans(text, spans))
	}
	// «Адрес» — пять кириллических букв, то есть 10 байт, плюс двоеточие и
	// пробел: значение начинается с 12-го байта. В рунах это было бы 7.
	const wantStart = 12
	wantEnd := wantStart + len(want)
	if int(spans[0].Start) != wantStart || int(spans[0].End) != wantEnd {
		t.Fatalf("спан = [%d, %d), ожидалось [%d, %d)", spans[0].Start, spans[0].End, wantStart, wantEnd)
	}
	if got := text[spans[0].Start:spans[0].End]; got != want {
		t.Fatalf("вырезка из doc.Text по спану = %q, ожидалось %q", got, want)
	}
}

// TestScanAddressSeveralInText проверяет, что два адреса в одном тексте не
// склеиваются в один спан.
