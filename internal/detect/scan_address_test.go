// Все адреса в тестах синтетические: улицы и номера домов вымышлены или взяты
// из общеизвестных топонимов, к реальному лицу ни один адрес не относится.

// addrMaskedCreditRequest — ожидаемая маска фразы «Клиент <ФИО> <дата>
// обратился за кредитом.»: общая для всех городов-фамилий.
const addrMaskedCreditRequest = "Клиент [ФИО] [ДАТА_РОЖДЕНИЯ] обратился за кредитом."

// expectPipelineMask сверяет маску полного конвейера с ожидаемой.
func expectPipelineMask(t *testing.T, text, want string) {
	t.Helper()
	if got := digitsMasked(t, text); got != want {
		t.Errorf(msgMaskWant, got, want)
	}
}

// addressWant — ожидаемый кандидат: точный текст спана и уверенность.
type addressWant struct {
	text string
	conf Confidence
}

func TestScanAddress(t *testing.T) {
	cases := []struct {
		name string
		text string
		// want — кандидаты, которые обязаны быть найдены.
		want []addressWant
		// noAddress — в тексте не должно быть ни одного кандидата на адрес.
		noAddress bool
	}{
		// AC-1: цепочка целиком одним спаном. Открывающий маркер «г.» в спан
		// не входит (CONTRACTS.md: служебное слово на границе значения),
		// внутренние «ул.», «д.», «кв.» — входят.
		{
			name: "полный адрес одним спаном",
			text: "г. Москва, ул. Ленина, д. 5, кв. 12",
			want: []addressWant{{"Москва, ул. Ленина, д. 5, кв. 12", Strong}},
		},
		// AC-2: индекс плюс город плюс улица с номером дома.
		{
			name: "адрес с индексом достоверен",
			text: "101000, Москва, Тверская 5",
			want: []addressWant{{"101000, Москва, Тверская 5", Certain}},
		},
		// Сокращение «пр.» после названия (замечание технического жюри 23.09,
		// S4): раньше в спан попадали только дом и квартира.
		{
			name: "проспект сокращением после названия",
			text: "г. Санкт-Петербург, Невский пр., д. 100, кв. 5",
			want: []addressWant{{"Санкт-Петербург, Невский пр., д. 100, кв. 5", Strong}},
		},
		// AC-3: слова вокруг адреса в спан не входят.
		{
			name: "служебные слова перед адресом вне спана",
			text: "проживает по адресу Санкт-Петербург, Невский проспект, 28",
			want: []addressWant{{"Санкт-Петербург, Невский проспект, 28", Strong}},
		},
		{
			name: "адрес в конце предложения",
			text: "Доставка на адрес Казань, ул. Баумана, д. 17, кв. 3 сегодня",
			want: []addressWant{{"Казань, ул. Баумана, д. 17, кв. 3", Strong}},
		},
		// AC-4: компоненты по отдельности.
		{
			name: "регион отдельным компонентом",
			text: "Заявка пришла из региона Московская область вчера",
			want: []addressWant{{"Московская область", Weak}},
		},
		{
			name: "индекс отдельным компонентом",
			text: "укажите индекс 143000 в анкете",
			want: []addressWant{{"143000", Weak}},
		},
		{
			name: "квартира отдельным компонентом",
			text: "домофон не работает, кв. 45 не отвечает",
			want: []addressWant{{"45", Weak}},
		},
		{
			name: "одинокий город из справочника при маркере",
			text: "Командировка в г. Новосибирск перенесена",
			want: []addressWant{{"Новосибирск", Weak}},
		},
		// Город без маркера, без дома и без слова об адресе — география речи,
		// а не адрес (T-65, строка 10; P4-11).
		{
			name:      "одинокий город без маркера не адрес",
			text:      "Командировка в Новосибирск перенесена",
			noAddress: true,
		},
		{
			name: "одинокий город после слова об адресе",
			text: "Адрес регистрации: Новосибирск",
			want: []addressWant{{"Новосибирск", Weak}},
		},
		// AC-5: регистр не влияет.
		{
			name: "верхний регистр",
			text: "Г. МОСКВА, УЛ. ЛЕНИНА, Д. 5",
			want: []addressWant{{"МОСКВА, УЛ. ЛЕНИНА, Д. 5", Strong}},
		},
		{
			name: "нижний регистр маркеров и город со справочника",
			text: "адрес: г.Казань, ул.Баумана, д.17",
			want: []addressWant{{"Казань, ул.Баумана, д.17", Strong}},
		},
		// AC-6: число без маркеров адресом не считается.
		{
			name:      "одиночное число не адрес",
			text:      "В корзине 5 яблок и 12 груш",
			noAddress: true,
		},
		{
			name:      "дата и сумма не адрес",
			text:      "Платёж 15000 рублей прошёл 03.07.2021 без ошибок",
			noAddress: true,
		},
		{
			name:      "топоним со строчной буквы не адрес",
			text:      "он вернулся в москва поздно",
			noAddress: true,
		},
		{
			name:      "название улицы без других компонентов цепочку не открывает",
			text:      "Тверская 5 звучит как загадка",
			noAddress: true,
		},
		// Составные топонимы.
		{
			name: "составной город через пробел",
			text: "Нижний Новгород, ул. Минина, д. 2",
			want: []addressWant{{"Нижний Новгород, ул. Минина, д. 2", Strong}},
		},
		{
			name: "составной город через дефис",
			text: "Ростов-на-Дону, пр-т Стачки, 10",
			want: []addressWant{{"Ростов-на-Дону, пр-т Стачки, 10", Strong}},
		},
		{
			name: "республика из справочника",
			text: "Республика Татарстан, г. Казань",
			want: []addressWant{{"Республика Татарстан, г. Казань", Strong}},
		},
		// Прочие формы компонентов.
		{
			name: "корпус и строение внутри цепочки",
			text: "Москва, ул. Мира, д. 5, корп. 2, кв. 7",
			want: []addressWant{{"Москва, ул. Мира, д. 5, корп. 2, кв. 7", Strong}},
		},
		{
			name: "шоссе и владение",
			text: "Химки, Ленинградское шоссе, влд. 12",
			want: []addressWant{{"Химки, Ленинградское шоссе, влд. 12", Strong}},
		},
		{
			name: "район и область",
			text: "Московская область, Одинцовский р-н, с. Юдино",
			want: []addressWant{{"Московская область, Одинцовский р-н, с. Юдино", Strong}},
		},
		{
			name: "буквенный индекс дома",
			text: "Тула, ул. Садовая, д. 5а",
			want: []addressWant{{"Тула, ул. Садовая, д. 5а", Strong}},
		},
		{
			name: "перевод строки разрывает цепочку",
			text: "г. Москва\nЛенина 5",
			want: []addressWant{{"Москва", Weak}},
		},
		// Адрес отделения банка регистрируется кандидатом: вето ставит T-10.
		{
			name: "адрес организации остаётся кандидатом",
			text: "Отделение банка: Москва, ул. Вавилова, д. 19",
			want: []addressWant{{"Москва, ул. Вавилова, д. 19", Strong}},
		},
	}

	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			spans := scanAddressText(t, tc.text)
			if tc.noAddress {
				if len(spans) != 0 {
					t.Fatalf("ожидалось отсутствие адреса, получено: %s", formatAddressSpans(tc.text, spans))
				}
				return
			}
			for _, w := range tc.want {
				if !hasAddressSpan(tc.text, spans, w) {
					t.Errorf("не найден спан %q (%s); получено: %s",
						w.text, w.conf, formatAddressSpans(tc.text, spans))
				}
			}
		})
	}
}

// TestScanAddressStreetForms — формы адреса из второго раунда технического
// жюри (N5, задача T-61): улица без города впереди, тип улицы после
// названия, «живу на <улица> <дом>», город в предложном падеже, «д.» как
// деревня, «ул. 8 Марта». Открывающие «Адрес:», «проживает», «г.», «ул.» в
// спан не входят, внутренние маркеры — входят, как и раньше.
func TestScanAddressStreetForms(t *testing.T) {
	cases := []struct {
		text string
		want addressWant
	}{
		{"Адрес: Кутузовский проспект, д. 30, кв. 15", addressWant{"Кутузовский проспект, д. 30, кв. 15", Strong}},
		{"Адрес: Кутузовский пр-т, д. 30, кв. 15", addressWant{"Кутузовский пр-т, д. 30, кв. 15", Strong}},
		{"Адрес: Ленинградское ш., д. 5", addressWant{"Ленинградское ш., д. 5", Strong}},
		{"Адрес: Сивцев Вражек пер., д. 5", addressWant{"Сивцев Вражек пер., д. 5", Strong}},
		{"Адрес: наб. реки Фонтанки, д. 10", addressWant{"реки Фонтанки, д. 10", Strong}},
		{"Адрес: 191023, Санкт-Петербург, наб. реки Мойки, д. 12", addressWant{"191023, Санкт-Петербург, наб. реки Мойки, д. 12", Certain}},
		{"Адрес: ул. 8 Марта, д. 14", addressWant{"8 Марта, д. 14", Strong}},
		{"Проживает: улица 8 Марта, 14-88", addressWant{"8 Марта, 14-88", Strong}},
		{"Я живу на Баумана 12, квартира 3.", addressWant{"Баумана 12, квартира 3", Strong}},
		{"Я живу на Баумана 12.", addressWant{"Баумана 12", Strong}},
		{"Прописан по Садовой 12, кв. 4.", addressWant{"Садовой 12, кв. 4", Strong}},
		{"Я живу на улице Ленина, дом 5", addressWant{"Ленина, дом 5", Strong}},
		{"Я живу в Казани на улице Баумана, дом 12, квартира 3.", addressWant{"Казани на улице Баумана, дом 12, квартира 3", Strong}},
		{"Адрес клиента: Казань, Баумана 12", addressWant{"Казань, Баумана 12", Strong}},
		{"Клиент проживает в Химках, ул. Молодёжная, 4.", addressWant{"Химках, ул. Молодёжная, 4", Strong}},
		{"Проживаю в Санкт-Петербурге, Невский пр., д. 100", addressWant{"Санкт-Петербурге, Невский пр., д. 100", Strong}},
		{"Живу в Твери на ул. Советской, 5", addressWant{"Твери на ул. Советской, 5", Strong}},
		{"Адрес: д. Ивановка, ул. Центральная, 5", addressWant{"Ивановка, ул. Центральная, 5", Strong}},
		{"проживает в г. Тула на ул. Советской, дом 5", addressWant{"Тула на ул. Советской, дом 5", Strong}},
		// Названная улица с домом — адрес и без города; без дома — нет.
		{"доставка: ул. Молодёжная, 4", addressWant{"Молодёжная, 4", Strong}},
		{"доставка: ул. Пушкина", addressWant{"Пушкина", Weak}},
	}
	for _, tc := range cases {
		t.Run(tc.text, func(t *testing.T) {
			spans := scanAddressText(t, tc.text)
			if !hasAddressSpan(tc.text, spans, tc.want) {
				t.Errorf("не найден спан %q (%s); получено: %s", tc.want.text, tc.want.conf, formatAddressSpans(tc.text, spans))
			}
		})
	}
}

