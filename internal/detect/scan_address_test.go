var (
	addressDictsOnce sync.Once
	addressDictsSet  *dict.Set
	addressDictsErr  error
)

// addressTestDicts загружает встроенные справочники один раз на пакет.
func addressTestDicts(tb testing.TB) *dict.Set {
	tb.Helper()
	addressDictsOnce.Do(func() { addressDictsSet, addressDictsErr = dict.Load() })
	if addressDictsErr != nil {
		tb.Fatalf(msgDictLoad, addressDictsErr)
	}
	return addressDictsSet
}

// scanAddressText прогоняет сканер по тексту и возвращает кандидатов.
func scanAddressText(tb testing.TB, text string) []Span {
	tb.Helper()
	doc := lex.Tokenize(text, nil)
	var out Candidates
	addressScanner{}.Scan(doc, addressTestDicts(tb), &out)
	return out.Spans
}

func hasAddressSpan(text string, spans []Span, w addressWant) bool {
	for _, s := range spans {
		if s.Type == pii.Address && s.Conf == w.conf && text[s.Start:s.End] == w.text {
			return true
		}
	}
	return false
}

func formatAddressSpans(text string, spans []Span) string {
	if len(spans) == 0 {
		return "(пусто)"
	}
	var b strings.Builder
	for i, s := range spans {
		if i > 0 {
			b.WriteString("; ")
		}
		b.WriteString("«")
		b.WriteString(text[s.Start:s.End])
		b.WriteString("» ")
		b.WriteString(s.Conf.String())
		b.WriteString(" ")
		b.WriteString(s.Rule)
	}
	return b.String()
}

