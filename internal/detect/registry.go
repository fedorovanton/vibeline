package detect

import "sort"

// registered — сканеры, подключённые в сборку.
//
// Регистрация через init позволяет добавить сканер новым файлом, не трогая
// общий список: параллельно работающие задачи не конфликтуют за один файл,
// а расширение набора типов ПД не требует правки ядра (ТЗ §3.2.1).
var registered []Scanner

// Register подключает сканер. Вызывается из init-функций файлов сканеров;
// после старта сервиса список только читается.
func Register(s Scanner) { registered = append(registered, s) }

// Registered возвращает подключённые сканеры, упорядоченные по имени.
//
// Порядок зафиксирован, чтобы результат не зависел от порядка инициализации
// файлов: движок всё равно разрешает перекрытия детерминированно, но
// воспроизводимость отладочных логов от этого выигрывает.
func Registered() []Scanner {
	out := make([]Scanner, len(registered))
	copy(out, registered)
	sort.Slice(out, func(i, j int) bool { return out[i].Name() < out[j].Name() })
	return out
}
