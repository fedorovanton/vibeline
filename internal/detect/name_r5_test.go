import "testing"

// Тесты раунда 5 жюри (T-80, ФИО-часть T-83). Все ФИО синтетические.

// nameR5Case — вход и значения, каждое из которых полный движок должен
// накрыть одним спаном ФИО целиком.
type nameR5Case struct {
	text string
	want []string
}

// nameR5Keep — вход и фрагмент, который не должен попасть под маску ФИО.
type nameR5Keep struct {
	text, keep string
}

func nameR5ExpectMasked(t *testing.T, cases []nameR5Case) {
	t.Helper()
	e := newFullEngine(t)
	for _, tc := range cases {
		t.Run(tc.text, func(t *testing.T) { nameExpectMasked(t, e, tc.text, tc.want...) })
	}
}

func nameR5ExpectKept(t *testing.T, cases []nameR5Keep) {
	t.Helper()
	e := newFullEngine(t)
	for _, tc := range cases {
		t.Run(tc.text, func(t *testing.T) { nameExpectKept(t, e, tc.text, tc.keep) })
	}
}

