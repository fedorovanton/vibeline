package mask

import (
	"crypto/hmac"
	"crypto/rand"
	"crypto/sha256"
	"encoding/binary"
	"os"
	"sync"

	"ai-gateway/internal/pii"
)

// Token — непрозрачная замена вида {{pii:a3f1c2d4}} (ТЗ §6, токенизация).
//
// Стратегия для потребителя, которому нельзя раскрывать модели даже категорию
// данных: из токена не выводится ни значение, ни тип. Всё, что модель может
// узнать, — что здесь стояло одно и то же значение или два разных.
//
// Обратное преобразование выполняется по сохранённому в Store соответствию,
// а не разбором токена: токен не содержит ничего, что можно было бы
// «расшифровать».
type Token struct{}

// Name возвращает имя стратегии.
func (Token) Name() string { return "token" }

// Mask возвращает токен, детерминированно выведенный из типа и значения.
//
// Детерминированность здесь не украшение, а условие контракта: маскирование
// объявлено чистой функцией от (payload, policy), и повтор прямого шага
// /process обязан дать побайтово тот же результат. Ключ фиксирован на время
// жизни процесса, состояния между запросами нет — стратегия безопасна для
// конкурентного использования.
//
// Номер значения seq в токен не входит намеренно: одно и то же значение даёт
// один и тот же токен и в разных запросах, и в разных потребителях — это
// делает токенизацию пригодной для сквозной корреляции без раскрытия данных.
//
// Токен — HMAC-SHA256 с секретным ключом, а не открытый хеш. Прежний FNV без
// ключа позволял восстановить короткое значение перебором: CVV из трёх цифр —
// за тысячу вычислений, ПИН — за десять тысяч (замечание технического жюри
// 23.09). С ключом перебор без ключа ничего не даёт.
func (Token) Mask(orig string, t pii.Type, _ int) string {
	mac := hmac.New(sha256.New, tokenKey())
	mac.Write([]byte{byte(t)})
	mac.Write([]byte(orig))
	var sum [sha256.Size]byte
	return formatToken(binary.BigEndian.Uint32(mac.Sum(sum[:0])))
}

// TokenKeyEnv — переменная окружения с ключом токенизации.
//
// Задать её стоит, если токены должны совпадать между перезапусками и
// экземплярами. Без неё ключ случайный на процесс: токены стабильны в пределах
// жизни процесса — этого хватает и идемпотентности /process, и восстановлению
// по Store, которое живёт столько же.
const TokenKeyEnv = "AIGW_TOKEN_KEY"

var tokenKeyOnce struct {
	sync.Once
	key []byte
}

// tokenKey читает ключ при первом обращении, а не при инициализации пакета:
// переменные из файла .env сервис выставляет уже после старта.
func tokenKey() []byte {
	tokenKeyOnce.Do(func() {
		if k := os.Getenv(TokenKeyEnv); k != "" {
			tokenKeyOnce.key = []byte(k)
			return
		}
		key := make([]byte, 32)
		if _, err := rand.Read(key); err != nil {
			// crypto/rand на поддерживаемых системах не отказывает; если всё
			// же отказал, работать с предсказуемым ключом нельзя.
			panic("mask: не удалось получить случайный ключ токенизации")
		}
		tokenKeyOnce.key = key
	})
	return tokenKeyOnce.key
}

const hexDigits = "0123456789abcdef"

// formatToken собирает строку токена без промежуточных аллокаций.
//
// Тридцати двух бит достаточно, чтобы различать значения одного запроса:
// при пределе max_spans в 20 000 различных значений совпадение маловероятно,
// а если оно произойдёт — две маски склеятся в одну. Обратный шаг /process
// это не ломает: он возвращает сохранённый оригинал целиком, не разбирая
// токены. Пострадать может только восстановление отдельных плейсхолдеров
// в ответе модели, где склеенная пара вернёт одно значение из двух.
func formatToken(v uint32) string {
	buf := [16]byte{'{', '{', 'p', 'i', 'i', ':', 0, 0, 0, 0, 0, 0, 0, 0, '}', '}'}
	for i := 0; i < 8; i++ {
		buf[6+i] = hexDigits[(v>>uint(28-4*i))&0xf]
	}
	return string(buf[:])
}

func init() { Register(Token{}) }
