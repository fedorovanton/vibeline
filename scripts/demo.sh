#!/usr/bin/env bash
#
# Демонстрация работы сервиса для проверки жюри.
#
# Прогоняет набор сценариев через POST /process: маскирование, точное
# восстановление и распознавание ловушек. Адрес сервиса задаётся первым
# аргументом либо переменной HOST.

set -euo pipefail

HOST="${1:-${HOST:-http://localhost:8080}}"

# Идентификатор прогона. Соответствие «payload_id → оригинал» живёт в сервисе
# до истечения TTL, и повторный прогон с тем же идентификатором, но изменённым
# текстом, пошёл бы по ветке «вход не совпал ни с чем»: сервис замаскировал бы
# его как новый вход, не трогая сохранённую запись, и сверка с оригиналом
# разошлась бы. Уникальный суффикс на запуск снимает это, а заодно разводит
# двух человек, гоняющих демонстрацию против одного сервиса.
#
# Переопределяется извне: RUN_ID=<значение> повторяет прогон с теми же
# идентификаторами — так проверяется повтор прямого шага.
RUN_ID="${RUN_ID:-$(date +%s)-$$}"

b()  { printf '\033[1m%s\033[0m\n' "$1"; }
dim(){ printf '\033[2m%s\033[0m\n' "$1"; }

call() {
  curl -sS -X POST "${HOST}/process" \
    -H 'Content-Type: application/json' \
    --data-binary "$(python3 -c 'import json,sys; print(json.dumps({"payload":sys.argv[1],"payload_id":sys.argv[2]}))' "$1" "$2")" \
  | python3 -c 'import json,sys; print(json.load(sys.stdin)["result"])'
}

roundtrip() {
  local text="$1" id="$2-${RUN_ID}" title="$3"
  b "── ${title}"
  dim "исходный текст:"
  echo "  ${text}"

  local masked restored
  masked="$(call "${text}" "${id}")"
  dim "замаскировано:"
  echo "  ${masked}"

  restored="$(call "${masked}" "${id}")"
  dim "восстановлено:"
  echo "  ${restored}"

  if [ "${restored}" = "${text}" ]; then
    printf '  \033[32m✓ совпадает с оригиналом побайтово\033[0m\n'
  else
    printf '  \033[31m✗ РАСХОЖДЕНИЕ С ОРИГИНАЛОМ\033[0m\n'
  fi
  echo
}

b "Сервис: ${HOST}"
curl -sS "${HOST}/healthz" && echo && echo

roundtrip \
"Клиент Иванов Иван Иванович, паспорт серия 4509 номер 123456, выдан ГУ МВД России по г. Москве, код подразделения 770-053, ИНН 500123456750, карта 4111 1111 1111 1111, cvv 123, тел. +7 916 123-45-67, почта ivan.petrov@example.com, родился 12 мая 1990 года, проживает: г. Москва, ул. Ленина, д. 5, кв. 12" \
"demo-full" \
"Полный набор реквизитов"

roundtrip \
"ПЕТРОВОЙ АННЕ СЕРГЕЕВНЕ, дата рождения 05/12/1985, паспорт 45 09 123456, снилс 112-233-445 95" \
"demo-case" \
"Верхний регистр, падежи, иной порядок компонентов даты"

roundtrip \
"Поэт Александр Пушкин жил на улице Мойки. Отделение банка: г. Москва, ул. Тверская, 7. Горячая линия 8-800-555-35-35, пишите на info@alfabank.ru. Договор подписан 01.02.2024." \
"demo-traps" \
"Ловушки: публичная персона, адрес отделения, линия поддержки"

roundtrip \
"Клиент Александр Пушкин, телефон +7 916 000-11-22, паспорт 4509 654321" \
"demo-namesake" \
"Однофамилец публичной персоны — обязан защищаться"

b "── Метрики"
curl -sS "${HOST}/metrics" | grep -E '^aigw_(pii_masked_total|requests_total|request_duration_seconds_count)' | head -20
echo

b "── Журнал"
dim "значений персональных данных в журнале нет: только типы, счётчики и длительности"
